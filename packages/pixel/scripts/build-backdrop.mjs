// Builds the page the app's WebView runs (src/backdrop-html.generated.ts): the engine's
// modules, transpiled with TypeScript and linked by a tiny require, inlined into one HTML
// string. Nothing loads from the network, so the page ships inside the JavaScript bundle and
// an update can change it. The pixel tests rebuild it and fail if the file is stale.
//
//   npm run build:backdrop --workspace=@app/pixel
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const SRC = new URL('../src/', import.meta.url)
const OUT = new URL('../src/backdrop-html.generated.ts', import.meta.url)
/** Every module the page needs; the last one is the entry. */
const MODULES = ['noise', 'dither', 'fields', 'students', 'scenes', 'backdrop', 'backdrop-page']

export function buildBackdropHtml() {
	const definitions = MODULES.map((name) => {
		const source = readFileSync(new URL(`${name}.ts`, SRC), 'utf8')
		const { outputText } = ts.transpileModule(source, {
			compilerOptions: {
				module: ts.ModuleKind.CommonJS,
				target: ts.ScriptTarget.ES2019,
				removeComments: true
			}
		})
		return `${JSON.stringify(`./${name}`)}:function(module,exports,require){${outputText}}`
	})
	const entry = `./${MODULES.at(-1)}`
	const script = `(function(){var defs={${definitions.join(',')}};var done={};function req(n){if(done[n])return done[n].exports;var m={exports:{}};done[n]=m;defs[n](m,m.exports,req);return m.exports}req(${JSON.stringify(entry)})})();`
	return (
		'<!doctype html><html><head><meta charset="utf-8">' +
		'<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">' +
		'<style>html,body{margin:0;height:100%;overflow:hidden;background:transparent}' +
		'canvas{display:block;width:100vw;height:100vh;image-rendering:pixelated}</style>' +
		`</head><body><canvas id="backdrop"></canvas><script>${script.replaceAll('</', '<\\/')}</script></body></html>`
	)
}

export function generatedModule(html = buildBackdropHtml()) {
	return (
		'// Generated by scripts/build-backdrop.mjs from the modules in this folder. Do not edit:\n' +
		'// run `npm run build:backdrop --workspace=@app/pixel` after changing the engine.\n' +
		`export const BACKDROP_HTML = ${JSON.stringify(html)}\n`
	)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(OUT, generatedModule())
	console.log(`Wrote ${fileURLToPath(OUT)}`)
}
